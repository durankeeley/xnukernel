#!/bin/bash
# gen-stubs.sh <missing-symbols-file> <output.c>
# Emits do-nothing stubs (return 0 / ENXIO-style failure) for kernel symbols that stock kexts import
# but the open-source XNU tree does not define (Skywalk, xcpm, ...).
set -eu
IN=$1; OUT=$2
{
echo '/* GENERATED by scripts/gen-stubs.sh from build/symcmp/missing-in-ours.sym. Do not edit. */'
echo '/* Each stub returns 0 / NULL. They exist only so kexts that import these symbols link. */'
echo '#define STUB(n, label) long n(void) __asm__(label); long n(void) { return 0; }'
i=0
while read -r sym; do
  [ -z "$sym" ] && continue
  i=$((i+1))
  echo "STUB(xcross_stub_$i, \"$sym\")"
done < "$IN"
} > "$OUT"
echo "wrote $(grep -c '^STUB(' "$OUT") stubs to $OUT"

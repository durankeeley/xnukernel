#!/usr/bin/env python3
"""Generate imm.inc: native intrinsic wrappers that need a compile-time immediate (palignr, pcmp[ie]str[im])."""
out=[]
out.append("static __m128i nat_alignr_x(__m128i d,__m128i s,int imm){switch(imm){")
for n in range(256): out.append(f"case {n}: return _mm_alignr_epi8(d,s,{n});")
out.append("}return d;}")
out.append("static __m64 nat_alignr_m(__m64 d,__m64 s,int imm){switch(imm){")
for n in range(256): out.append(f"case {n}: return _mm_alignr_pi8(d,s,{n});")
out.append("}return d;}")
def sw(name, ret, args, call):
    out.append(f"static {ret} {name}({args},int imm){{switch(imm){{")
    for n in range(128): out.append(f"case {n}: return {call.replace('IMM',str(n))};")
    out.append("}return " + ("_mm_setzero_si128()" if ret=="__m128i" else "0") + ";}")
sw("nat_cmpistri","int","__m128i a,__m128i b","_mm_cmpistri(a,b,IMM)")
sw("nat_cmpistrc","int","__m128i a,__m128i b","_mm_cmpistrc(a,b,IMM)")
sw("nat_cmpistrz","int","__m128i a,__m128i b","_mm_cmpistrz(a,b,IMM)")
sw("nat_cmpistrs","int","__m128i a,__m128i b","_mm_cmpistrs(a,b,IMM)")
sw("nat_cmpistro","int","__m128i a,__m128i b","_mm_cmpistro(a,b,IMM)")
sw("nat_cmpistrm","__m128i","__m128i a,__m128i b","_mm_cmpistrm(a,b,IMM)")
sw("nat_cmpestri","int","__m128i a,int la,__m128i b,int lb","_mm_cmpestri(a,la,b,lb,IMM)")
sw("nat_cmpestrc","int","__m128i a,int la,__m128i b,int lb","_mm_cmpestrc(a,la,b,lb,IMM)")
sw("nat_cmpestrz","int","__m128i a,int la,__m128i b,int lb","_mm_cmpestrz(a,la,b,lb,IMM)")
sw("nat_cmpestrs","int","__m128i a,int la,__m128i b,int lb","_mm_cmpestrs(a,la,b,lb,IMM)")
sw("nat_cmpestro","int","__m128i a,int la,__m128i b,int lb","_mm_cmpestro(a,la,b,lb,IMM)")
sw("nat_cmpestrm","__m128i","__m128i a,int la,__m128i b,int lb","_mm_cmpestrm(a,la,b,lb,IMM)")

# ---- SSE4.1 -------------------------------------------------------------------------------------------------
def sw41(name, ret, args, call, n):
    out.append(f"static {ret} {name}({args},int imm){{switch(imm){{")
    for k in range(n): out.append(f"case {k}: return {call.replace('IMM',str(k))};")
    zero = {"__m128i":"_mm_setzero_si128()","__m128":"_mm_setzero_ps()","__m128d":"_mm_setzero_pd()"}.get(ret,"0")
    out.append("}return "+zero+";}")
V="__m128i d,__m128i s"
sw41("nat_pblendw","__m128i",V,"_mm_blend_epi16(d,s,IMM)",256)
sw41("nat_blendps","__m128","__m128 d,__m128 s","_mm_blend_ps(d,s,IMM)",16)
sw41("nat_blendpd","__m128d","__m128d d,__m128d s","_mm_blend_pd(d,s,IMM)",4)
sw41("nat_dpps","__m128","__m128 d,__m128 s","_mm_dp_ps(d,s,IMM)",256)
sw41("nat_dppd","__m128d","__m128d d,__m128d s","_mm_dp_pd(d,s,IMM)",256)
sw41("nat_insertps","__m128","__m128 d,__m128 s","_mm_insert_ps(d,s,IMM)",256)
sw41("nat_mpsadbw","__m128i",V,"_mm_mpsadbw_epu8(d,s,IMM)",8)
sw41("nat_roundps","__m128","__m128 d,__m128 s","_mm_round_ps(s,IMM)",16)
sw41("nat_roundpd","__m128d","__m128d d,__m128d s","_mm_round_pd(s,IMM)",16)
sw41("nat_roundss","__m128","__m128 d,__m128 s","_mm_round_ss(d,s,IMM)",16)
sw41("nat_roundsd","__m128d","__m128d d,__m128d s","_mm_round_sd(d,s,IMM)",16)
sw41("nat_pinsrb","__m128i","__m128i d,int v","_mm_insert_epi8(d,v,IMM)",16)
sw41("nat_pinsrd","__m128i","__m128i d,int v","_mm_insert_epi32(d,v,IMM)",4)
sw41("nat_pinsrq","__m128i","__m128i d,long long v","_mm_insert_epi64(d,v,IMM)",2)
sw41("nat_pextrb","int","__m128i s","_mm_extract_epi8(s,IMM)",16)
sw41("nat_pextrd","int","__m128i s","_mm_extract_epi32(s,IMM)",4)
sw41("nat_pextrq","long long","__m128i s","_mm_extract_epi64(s,IMM)",2)
open("imm.inc","w").write("\n".join(out)+"\n")

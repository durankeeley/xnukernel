#!/usr/bin/env python3
"""gen-iig-abi.py [symbol-list (default scripts/iig-abi-symbols.txt, produced by missing-exports.py)] -- generate src/xnu/libkern/xcross_iig_abi.c.
Defines (as module-level asm) every symbol that stock-Tahoe kexts import from the kernel but that this build lacks (see
scripts/missing-exports.py): the DriverKit/iig ABI (wrappers taking a trailing OSDispatchMethod, *_Invoke, Dispatch/_Dispatch) and the
Apple-internal libtb (Thunderbolt) message API. Wrappers tail-jump to the existing implementation when one is present; everything
else returns kIOReturnUnsupported (0xe00002c7), which is correct for a machine without dexts or Thunderbolt."""
import subprocess, sys
need = open(sys.argv[1] if len(sys.argv) > 1 else 'scripts/iig-abi-symbols.txt').read().split()
STOCK = 'build/kdk-real/kdk/System/Library/Kernels/kernel.development'
OURS = 'out/kernel.tahoe-unstripped.x86_64'
def defined(p):
    d = {}
    for l in subprocess.run(['llvm-nm', '--defined-only', '--extern-only', p], capture_output=True, text=True).stdout.splitlines():
        t = l.split()
        if len(t) == 3: d[t[2]] = t[1]
    return d
st, ours = defined(STOCK), defined(OURS)
SUP = 'PFiP15OSMetaClassBase5IORPCE'
out = ['/* GENERATED by scripts/gen-iig-abi.py -- do not edit. See that script for what this is and why. */\n',
       '__asm__(\n', '".text\\n"\n']
alias = stub = data = 0
SKIP = ('OSAction_IOUserClient_KernelCompletion',)   # a real C++ class in iokit/Kernel/xcross_osaction.cpp
for s in sorted(need):
    if any(k in s for k in SKIP) and st.get(s) not in ('T', 't'):
        continue
    if st.get(s) not in ('T', 't'):
        data += 1
        continue
    base = s[:-len(SUP)] if s.endswith(SUP) else None
    out.append('".globl %s\\n.p2align 4\\n%s:\\n"\n' % (s, s))
    if base and base in ours:
        out.append('"  jmp %s\\n"\n' % base); alias += 1
    else:
        out.append('"  movl $0xe00002c7, %eax\\n  ret\\n"\n'); stub += 1
out.append('".data\\n.p2align 4\\n"\n')
for s in sorted(need):
    if st.get(s) in ('T', 't') or any(k in s for k in SKIP): continue
    out.append('".globl %s\\n%s:\\n  .space 512\\n"\n' % (s, s))
out.append(');\n')
open('src/xnu/libkern/xcross_iig_abi.c', 'w').write(''.join(out))
print('aliases %d, unsupported stubs %d, zeroed data %d' % (alias, stub, data))
